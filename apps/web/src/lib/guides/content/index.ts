/**
 * Optional per-locale overlays. Import translated modules here when they exist;
 * any missing slug falls back to the English module.
 */
const LOCALE_OVERLAYS: Record<string, Partial<Record<GuideSlug, GuideModule>>> =
  {
    es: ES_BY_SLUG,
    fr: FR_BY_SLUG,
    pt: PT_BY_SLUG,
    de: DE_BY_SLUG,
    ru: RU_BY_SLUG,
  };

const LOCALES_WITH_OVERLAYS = new Set(["es", "fr", "pt", "de", "ru"]);

export function loadGuidesForLocale(locale: string): GuideModule[] {
  if (locale === "en" || !LOCALES_WITH_OVERLAYS.has(locale)) {
    return GUIDE_SLUGS.map((slug) => EN_BY_SLUG[slug]);
  }

  const overlay = LOCALE_OVERLAYS[locale] ?? {};
  return GUIDE_SLUGS.map((slug) => overlay[slug] ?? EN_BY_SLUG[slug]);
}
